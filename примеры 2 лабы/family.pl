% Правило 1: получить всех родителей указанного ребёнка одним списком.
parents_of(Child, Parents) :-
    findall(Parent, родитель(Parent, Child), Parents).

% Правило 2: собрать все записи базы знаний.
all_pairs(Pairs) :-
    findall(Parent-Child, родитель(Parent, Child), Pairs).

% Правило 3: вывести новое отношение по цепочке из двух фактов.
grandparent(Grandparent, Child) :-
    родитель(Grandparent, Parent),
    родитель(Parent, Child).

% Два предложения одного предиката person/1.
person(Name) :- родитель(Name, _).
person(Name) :- родитель(_, Name).

% sort/2 удаляет повторы: Марина встречается в нескольких записях.
all_people(People) :-
    findall(Name, person(Name), Names),
    sort(Names, People).

show_pairs :-
    forall(родитель(Parent, Child),
           format('~w -> ~w~n', [Parent, Child])).
